//! Persistence for `daemon.toml` and the identities Vulcan generates for it.
//!
//! `daemon.toml` holds only owner intent, so it can be written by hand,
//! rendered by configuration management, or copied to another device. The
//! identities Vulcan generates for its declarations (vault registration IDs
//! and named-remote instance IDs) live in `daemon.identities.toml` beside it.
//! Writes to `daemon.toml` merge into the existing document, so comments,
//! ordering, and formatting survive CLI mutations
//! (`docs/specs/declarative-device-config.md`).

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use toml_edit::{ArrayOfTables, DocumentMut, Item, Table, Value};
use ulid::Ulid;

pub(crate) const IDENTITIES_FILE: &str = "daemon.identities.toml";

const IDENTITIES_HEADER: &str = "\
# Generated by Vulcan: identities of the vaults and named remotes declared in
# daemon.toml. API tokens, scan state and OAuth grants refer to them. Do not
# edit this file or copy it to another device.
";

/// Keys Vulcan generates and keeps out of `daemon.toml`, per array of tables.
const GENERATED_KEYS: [(&str, &str); 2] =
    [("vault", "registration_id"), ("mcp_remote", "instance_id")];

#[derive(Debug, Default, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub(crate) struct Identities {
    #[serde(default, rename = "vault", skip_serializing_if = "BTreeMap::is_empty")]
    pub vaults: BTreeMap<String, VaultIdentity>,
    #[serde(
        default,
        rename = "mcp_remote",
        skip_serializing_if = "BTreeMap::is_empty"
    )]
    pub mcp_remotes: BTreeMap<String, McpRemoteIdentity>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub(crate) struct VaultIdentity {
    pub registration_id: Ulid,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub(crate) struct McpRemoteIdentity {
    pub instance_id: Ulid,
}

#[must_use]
pub(crate) fn identities_path(config_path: &Path) -> PathBuf {
    config_path.with_file_name(IDENTITIES_FILE)
}

pub(crate) fn parse_identities(source: Option<&str>) -> Result<Identities, String> {
    source.map_or_else(
        || Ok(Identities::default()),
        |source| toml::from_str(source).map_err(|error| error.to_string()),
    )
}

pub(crate) fn render_identities(identities: &Identities) -> Result<String, String> {
    let body = toml::to_string_pretty(identities).map_err(|error| error.to_string())?;
    Ok(format!("{IDENTITIES_HEADER}\n{body}"))
}

/// Whether a `daemon.toml` document still carries generated identities, as
/// files written before identities moved out do.
#[must_use]
pub(crate) fn has_generated_keys(source: &str) -> bool {
    source.parse::<DocumentMut>().is_ok_and(|document| {
        GENERATED_KEYS.iter().any(|(array, key)| {
            document
                .get(array)
                .and_then(Item::as_array_of_tables)
                .is_some_and(|tables| tables.iter().any(|table| table.contains_key(key)))
        })
    })
}

/// Removes generated identities from a `daemon.toml` document and changes
/// nothing else, for the one-time migration of older files.
pub(crate) fn strip_generated(source: &str) -> Result<String, String> {
    let mut document = source
        .parse::<DocumentMut>()
        .map_err(|error| error.to_string())?;
    strip_generated_keys(&mut document);
    Ok(document.to_string())
}

/// Renders `config` for `daemon.toml` without generated identities. With an
/// existing document, only what changed is rewritten: comments, key order,
/// and value formatting of unchanged entries are kept.
pub(crate) fn render_config<T: Serialize>(
    existing: Option<&str>,
    config: &T,
) -> Result<String, String> {
    let rendered = toml::to_string_pretty(config).map_err(|error| error.to_string())?;
    let mut desired = rendered
        .parse::<DocumentMut>()
        .map_err(|error| error.to_string())?;
    strip_generated_keys(&mut desired);
    drop_empty_declaration_arrays(&mut desired);
    let Some(existing) = existing else {
        return Ok(desired.to_string());
    };
    let mut document = existing
        .parse::<DocumentMut>()
        .map_err(|error| error.to_string())?;
    strip_generated_keys(&mut document);
    let mut next_position = max_position(document.as_table()) + 1;
    merge_table(
        document.as_table_mut(),
        desired.as_table(),
        &mut next_position,
    );
    Ok(document.to_string())
}

/// The serializer writes an empty `vault = []` or `mcp_remote = []` when
/// none is declared; leave such a key out of the file instead.
fn drop_empty_declaration_arrays(document: &mut DocumentMut) {
    for (array, _) in GENERATED_KEYS {
        let empty = match document.get(array) {
            Some(Item::Value(Value::Array(values))) => values.is_empty(),
            Some(Item::ArrayOfTables(tables)) => tables.is_empty(),
            _ => false,
        };
        if empty {
            document.remove(array);
        }
    }
}

fn strip_generated_keys(document: &mut DocumentMut) {
    for (array, key) in GENERATED_KEYS {
        if let Some(tables) = document
            .get_mut(array)
            .and_then(Item::as_array_of_tables_mut)
        {
            for table in tables.iter_mut() {
                table.remove(key);
            }
        }
    }
}

fn merge_table(existing: &mut Table, desired: &Table, next_position: &mut usize) {
    let stale = existing
        .iter()
        .map(|(key, _)| key.to_string())
        .filter(|key| !desired.contains_key(key))
        .collect::<Vec<_>>();
    for key in stale {
        existing.remove(&key);
    }
    for (key, wanted) in desired {
        if let Some(current) = existing.get_mut(key) {
            merge_item(current, wanted, next_position);
        } else {
            let mut item = wanted.clone();
            assign_positions(&mut item, next_position);
            existing.insert(key, item);
        }
    }
}

fn merge_item(current: &mut Item, wanted: &Item, next_position: &mut usize) {
    match (&mut *current, wanted) {
        (Item::Table(current), Item::Table(wanted)) => {
            merge_table(current, wanted, next_position);
        }
        (Item::ArrayOfTables(current), Item::ArrayOfTables(wanted)) => {
            merge_array_of_tables(current, wanted, next_position);
        }
        (Item::Value(current), Item::Value(wanted)) => merge_value(current, wanted),
        // An owner may write a subtable inline; keep that form.
        (Item::Value(current @ Value::InlineTable(_)), Item::Table(wanted)) => {
            merge_value(
                current,
                &Value::InlineTable(wanted.clone().into_inline_table()),
            );
        }
        (current, wanted) => {
            let mut item = wanted.clone();
            assign_positions(&mut item, next_position);
            *current = item;
        }
    }
}

fn merge_value(current: &mut Value, wanted: &Value) {
    if values_equal(current, wanted) || home_relative_equal(current, wanted) {
        return;
    }
    let decor = current.decor().clone();
    *current = wanted.clone();
    *current.decor_mut() = decor;
}

/// Matches array elements by their `id`, falling back to position, so editing
/// one vault or remote leaves the others' formatting untouched.
fn merge_array_of_tables(
    current: &mut ArrayOfTables,
    wanted: &ArrayOfTables,
    next_position: &mut usize,
) {
    let mut previous = current.iter().cloned().map(Some).collect::<Vec<_>>();
    let mut merged = ArrayOfTables::new();
    for (index, table) in wanted.iter().enumerate() {
        let matching = match table_id(table) {
            Some(id) => previous
                .iter()
                .position(|candidate| candidate.as_ref().and_then(table_id) == Some(id)),
            None => previous
                .get(index)
                .and_then(Option::as_ref)
                .filter(|candidate| table_id(candidate).is_none())
                .map(|_| index),
        };
        if let Some(mut existing) = matching.and_then(|position| previous[position].take()) {
            merge_table(&mut existing, table, next_position);
            merged.push(existing);
        } else {
            let mut table = table.clone();
            assign_table_positions(&mut table, next_position);
            merged.push(table);
        }
    }
    // Array order is file order. When kept and new elements no longer appear
    // in the wanted order, move the whole array after the existing tables.
    if !in_file_order(&merged) {
        for table in merged.iter_mut() {
            assign_table_positions(table, next_position);
        }
    }
    *current = merged;
}

fn in_file_order(tables: &ArrayOfTables) -> bool {
    let mut previous_end = None;
    for table in tables {
        let Some(start) = table.position() else {
            return false;
        };
        if previous_end.is_some_and(|end| start <= end) {
            return false;
        }
        previous_end = Some(start.max(max_position(table)));
    }
    true
}

/// A path written as `~/...` is loaded expanded; keep the owner's form when
/// it still names the same path.
fn home_relative_equal(current: &Value, wanted: &Value) -> bool {
    match (current, wanted) {
        (Value::String(current), Value::String(wanted)) => {
            current.value().starts_with('~')
                && vulcan_core::config::expand_home(current.value()) == Path::new(wanted.value())
        }
        _ => false,
    }
}

fn table_id(table: &Table) -> Option<&str> {
    table.get("id").and_then(Item::as_str)
}

fn values_equal(left: &Value, right: &Value) -> bool {
    match (left, right) {
        (Value::String(left), Value::String(right)) => left.value() == right.value(),
        (Value::Integer(left), Value::Integer(right)) => left.value() == right.value(),
        (Value::Float(left), Value::Float(right)) => {
            left.value().to_bits() == right.value().to_bits()
        }
        (Value::Boolean(left), Value::Boolean(right)) => left.value() == right.value(),
        (Value::Datetime(left), Value::Datetime(right)) => left.value() == right.value(),
        (Value::Array(left), Value::Array(right)) => {
            left.len() == right.len()
                && left
                    .iter()
                    .zip(right.iter())
                    .all(|(left, right)| values_equal(left, right))
        }
        (Value::InlineTable(left), Value::InlineTable(right)) => {
            left.len() == right.len()
                && left.iter().all(|(key, value)| {
                    right
                        .get(key)
                        .is_some_and(|other| values_equal(value, other))
                })
        }
        _ => false,
    }
}

/// Tables carried over from the freshly rendered document keep that
/// document's positions; renumber them so they follow the existing ones.
fn assign_positions(item: &mut Item, next_position: &mut usize) {
    match item {
        Item::Table(table) => assign_table_positions(table, next_position),
        Item::ArrayOfTables(tables) => {
            for table in tables.iter_mut() {
                assign_table_positions(table, next_position);
            }
        }
        Item::None | Item::Value(_) => {}
    }
}

fn assign_table_positions(table: &mut Table, next_position: &mut usize) {
    table.set_position(*next_position);
    *next_position += 1;
    for (_, item) in table.iter_mut() {
        assign_positions(item, next_position);
    }
}

fn max_position(table: &Table) -> usize {
    table
        .iter()
        .map(|(_, item)| match item {
            Item::Table(table) => table.position().unwrap_or(0).max(max_position(table)),
            Item::ArrayOfTables(tables) => tables
                .iter()
                .map(|table| table.position().unwrap_or(0).max(max_position(table)))
                .max()
                .unwrap_or(0),
            Item::None | Item::Value(_) => 0,
        })
        .max()
        .unwrap_or(0)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
    struct Sample {
        bind: String,
        #[serde(default, skip_serializing_if = "Option::is_none")]
        notifications: Option<Notifications>,
        #[serde(default, rename = "vault")]
        vaults: Vec<Vault>,
        #[serde(default, rename = "mcp_remote")]
        remotes: Vec<Remote>,
    }

    #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
    struct Notifications {
        enabled: bool,
    }

    #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
    struct Vault {
        id: String,
        #[serde(default)]
        registration_id: Option<String>,
        path: String,
        #[serde(default, skip_serializing_if = "Vec::is_empty")]
        groups: Vec<String>,
    }

    #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
    struct Remote {
        id: String,
        #[serde(default)]
        instance_id: Option<String>,
        bind: String,
        authentication: Authentication,
    }

    #[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
    struct Authentication {
        identity: String,
    }

    const HAND_WRITTEN: &str = r#"# Normandy daemon
bind = "127.0.0.1:3210" # loopback only

[[vault]]
# my main wiki
id = "grimoire"
registration_id = "01M1VGCJ78TTEENPQ908PPQ6T6"
path = "/home/eric/wikis/grimoire"
groups = [ "daily",   "work" ]

[[vault]]
id = "stories"
path = "/home/eric/wikis/stories"

[[mcp_remote]]
id = "grimoire"
instance_id = "01M6SQPPJPNJ0TV6RMZXDCKMXJ"
bind = "127.0.0.1:8765"
authentication = { identity = "https://eric.example/" }
"#;

    fn parsed(source: &str) -> Sample {
        toml::from_str(source).expect("valid sample")
    }

    #[test]
    fn unchanged_config_keeps_the_document_apart_from_generated_keys() {
        let config = parsed(HAND_WRITTEN);
        let rendered = render_config(Some(HAND_WRITTEN), &config).unwrap();
        let expected = HAND_WRITTEN
            .replace("registration_id = \"01M1VGCJ78TTEENPQ908PPQ6T6\"\n", "")
            .replace("instance_id = \"01M6SQPPJPNJ0TV6RMZXDCKMXJ\"\n", "");
        assert_eq!(rendered, expected);
        assert!(has_generated_keys(HAND_WRITTEN));
        assert!(!has_generated_keys(&rendered));
    }

    #[test]
    fn a_change_rewrites_only_the_changed_value_and_keeps_its_comment() {
        let mut config = parsed(HAND_WRITTEN);
        config.bind = "127.0.0.1:4000".to_string();
        config.remotes[0].bind = "100.102.174.182:8765".to_string();
        let rendered = render_config(Some(HAND_WRITTEN), &config).unwrap();
        assert!(
            rendered.starts_with("# Normandy daemon\nbind = \"127.0.0.1:4000\" # loopback only\n")
        );
        assert!(rendered.contains("# my main wiki\nid = \"grimoire\""));
        assert!(rendered.contains("groups = [ \"daily\",   \"work\" ]"));
        assert!(rendered.contains("bind = \"100.102.174.182:8765\""));
        assert!(rendered.contains("authentication = { identity = \"https://eric.example/\" }"));
        assert_round_trip(&rendered, &config);
    }

    #[test]
    fn adding_and_removing_entries_keeps_the_rest_of_the_document() {
        let mut config = parsed(HAND_WRITTEN);
        config.vaults.remove(1);
        config.vaults.push(Vault {
            id: "recipes".to_string(),
            registration_id: Some("01M7AAAAAAAAAAAAAAAAAAAAAA".to_string()),
            path: "/home/eric/wikis/recipes".to_string(),
            groups: Vec::new(),
        });
        config.notifications = Some(Notifications { enabled: true });
        config.remotes[0].authentication.identity = "https://other.example/".to_string();
        let rendered = render_config(Some(HAND_WRITTEN), &config).unwrap();
        assert!(rendered.contains("# my main wiki"));
        assert!(!rendered.contains("stories"));
        assert!(!rendered.contains("01M7AAAAAAAAAAAAAAAAAAAAAA"));
        assert!(rendered.contains("authentication = { identity = \"https://other.example/\" }"));
        assert_round_trip(&rendered, &config);
    }

    #[test]
    fn a_new_entry_sorted_before_existing_ones_keeps_array_order() {
        let mut config = parsed(HAND_WRITTEN);
        config.vaults.insert(
            0,
            Vault {
                id: "archive".to_string(),
                registration_id: None,
                path: "/home/eric/wikis/archive".to_string(),
                groups: Vec::new(),
            },
        );
        let rendered = render_config(Some(HAND_WRITTEN), &config).unwrap();
        assert!(rendered.contains("# my main wiki"));
        assert_round_trip(&rendered, &config);
    }

    #[test]
    fn stripping_removes_only_generated_keys() {
        let stripped = strip_generated(HAND_WRITTEN).unwrap();
        assert_eq!(
            stripped,
            HAND_WRITTEN
                .replace("registration_id = \"01M1VGCJ78TTEENPQ908PPQ6T6\"\n", "")
                .replace("instance_id = \"01M6SQPPJPNJ0TV6RMZXDCKMXJ\"\n", "")
        );
    }

    #[test]
    fn a_new_file_is_rendered_without_generated_keys() {
        let config = parsed(HAND_WRITTEN);
        let rendered = render_config(None, &config).unwrap();
        assert!(!has_generated_keys(&rendered));
        assert_round_trip(&rendered, &config);
    }

    #[test]
    fn identities_round_trip_with_a_header() {
        let mut identities = Identities::default();
        identities.vaults.insert(
            "grimoire".to_string(),
            VaultIdentity {
                registration_id: Ulid::new(),
            },
        );
        identities.mcp_remotes.insert(
            "grimoire".to_string(),
            McpRemoteIdentity {
                instance_id: Ulid::new(),
            },
        );
        let rendered = render_identities(&identities).unwrap();
        assert!(rendered.starts_with("# Generated by Vulcan"));
        assert_eq!(parse_identities(Some(&rendered)).unwrap(), identities);
        assert_eq!(parse_identities(None).unwrap(), Identities::default());
    }

    fn assert_round_trip(rendered: &str, config: &Sample) {
        let mut expected = config.clone();
        for vault in &mut expected.vaults {
            vault.registration_id = None;
        }
        for remote in &mut expected.remotes {
            remote.instance_id = None;
        }
        let reparsed: Sample =
            toml::from_str(rendered).unwrap_or_else(|error| panic!("{error}\n{rendered}"));
        assert_eq!(reparsed, expected, "{rendered}");
    }
}
