//! Persistence for `daemon.toml` and the identities Vulcan generates for it.
//!
//! `daemon.toml` holds only owner intent, so it can be written by hand,
//! rendered by configuration management, or copied to another device. The
//! identities Vulcan generates for its declarations (vault registration IDs
//! and named-remote instance IDs) live in `daemon.identities.toml` beside it.
//! Writes to `daemon.toml` merge into the existing document, so comments,
//! ordering, and formatting survive CLI mutations
//! (`docs/specs/declarative-device-config.md`). The daemon registry and the
//! CLI's config commands share this writer and [`DaemonConfigLock`].

use serde::{Deserialize, Serialize};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use toml_edit::{ArrayOfTables, DocumentMut, Item, Table, Value};
use ulid::Ulid;

pub const IDENTITIES_FILE: &str = "daemon.identities.toml";

const IDENTITIES_HEADER: &str = "\
# Generated by Vulcan: identities of the vaults and named remotes declared in
# daemon.toml. API tokens, scan state and OAuth grants refer to them. Do not
# edit this file or copy it to another device.
";

/// Keys Vulcan generates and keeps out of `daemon.toml`, per array of tables.
const GENERATED_KEYS: [(&str, &str); 2] =
    [("vault", "registration_id"), ("mcp_remote", "instance_id")];

/// Exclusive lock on `daemon.toml` and its identities file, held across a
/// read-modify-write by every writer.
pub struct DaemonConfigLock {
    _file: std::fs::File,
}

impl DaemonConfigLock {
    pub fn acquire(config_path: &Path) -> std::io::Result<Self> {
        use fs2::FileExt;
        let parent = config_path.parent().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::InvalidInput,
                "daemon config path has no parent directory",
            )
        })?;
        std::fs::create_dir_all(parent)?;
        let file = std::fs::OpenOptions::new()
            .create(true)
            .read(true)
            .write(true)
            .truncate(false)
            .open(parent.join("daemon.toml.lock"))?;
        file.lock_exclusive()?;
        Ok(Self { _file: file })
    }
}

static MANAGED_EDITS_ALLOWED: std::sync::atomic::AtomicBool =
    std::sync::atomic::AtomicBool::new(false);

/// Lets this process edit a `daemon.toml` that names an owner in
/// `managed_by` (`--force-local-edit`). The next render by that owner
/// reverts such an edit.
pub fn allow_managed_edits(allowed: bool) {
    MANAGED_EDITS_ALLOWED.store(allowed, std::sync::atomic::Ordering::SeqCst);
}

#[must_use]
pub fn managed_edits_allowed() -> bool {
    MANAGED_EDITS_ALLOWED.load(std::sync::atomic::Ordering::SeqCst)
}

static PENDING_WARNINGS: std::sync::Mutex<Vec<String>> = std::sync::Mutex::new(Vec::new());

/// Warnings from forced edits of a managed file, for the CLI to print once
/// the command finishes.
pub fn take_warnings() -> Vec<String> {
    std::mem::take(&mut *PENDING_WARNINGS.lock().expect("warning queue"))
}

pub fn push_warning(warning: String) {
    PENDING_WARNINGS
        .lock()
        .expect("warning queue")
        .push(warning);
}

/// The owner a rendered `daemon.toml` names in its top-level `managed_by`.
#[must_use]
pub fn managed_by(source: &str) -> Option<String> {
    toml::from_str::<toml::Value>(source)
        .ok()?
        .get("managed_by")?
        .as_str()
        .map(ToOwned::to_owned)
}

/// Refuses an edit of a file managed by configuration management, unless
/// edits were forced, and names the TOML to add to the owner's source.
/// Returns a warning to print when a forced edit goes ahead.
pub fn check_managed_edit(
    config_path: &Path,
    existing: Option<&str>,
    before: &toml::Value,
    after: &toml::Value,
) -> Result<Option<String>, String> {
    let Some(owner) = existing.and_then(managed_by) else {
        return Ok(None);
    };
    if before == after {
        return Ok(None);
    }
    let snippet = change_snippet(before, after);
    if managed_edits_allowed() {
        return Ok(Some(format!(
            "{} is managed by {owner}; edited it anyway, and the next render by {owner} reverts this unless its source has:\n{snippet}",
            config_path.display()
        )));
    }
    Err(format!(
        "{} is managed by {owner}; add this to its source instead (or pass --force-local-edit for an emergency edit that its next render reverts):\n{snippet}",
        config_path.display()
    ))
}

/// The TOML that turns `before` into `after`: changed top-level values and
/// tables, and of an array of tables only the entries (matched by `id`) that
/// are new or changed. Removed entries and keys are listed as comments.
#[must_use]
pub fn change_snippet(before: &toml::Value, after: &toml::Value) -> String {
    let empty = toml::map::Map::new();
    let before = before.as_table().unwrap_or(&empty);
    let after = after.as_table().unwrap_or(&empty);
    let mut changed = toml::map::Map::new();
    let mut removed = Vec::new();
    for (key, value) in after {
        let previous = before.get(key);
        if previous == Some(value) {
            continue;
        }
        match (value, previous) {
            (toml::Value::Array(entries), Some(toml::Value::Array(old)))
                if entries.iter().all(toml::Value::is_table) =>
            {
                let entry_id = |entry: &toml::Value| entry.get("id").cloned();
                let fresh = entries
                    .iter()
                    .filter(|entry| !old.contains(entry))
                    .cloned()
                    .collect::<Vec<_>>();
                for gone in old.iter().filter(|entry| {
                    !entries
                        .iter()
                        .any(|candidate| entry_id(candidate) == entry_id(entry))
                }) {
                    let id = gone.get("id").and_then(toml::Value::as_str).unwrap_or("?");
                    removed.push(format!("remove the [[{key}]] entry with id = \"{id}\""));
                }
                if !fresh.is_empty() {
                    changed.insert(key.clone(), toml::Value::Array(fresh));
                }
            }
            _ => {
                changed.insert(key.clone(), value.clone());
            }
        }
    }
    for key in before.keys().filter(|key| !after.contains_key(*key)) {
        removed.push(format!("remove `{key}`"));
    }
    let mut snippet = toml::to_string_pretty(&toml::Value::Table(changed)).unwrap_or_default();
    for line in removed {
        snippet.push_str("# ");
        snippet.push_str(&line);
        snippet.push('\n');
    }
    snippet
}

#[derive(Debug, Default, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct Identities {
    #[serde(default, rename = "vault", skip_serializing_if = "BTreeMap::is_empty")]
    pub vaults: BTreeMap<String, VaultIdentity>,
    #[serde(
        default,
        rename = "mcp_remote",
        skip_serializing_if = "BTreeMap::is_empty"
    )]
    pub mcp_remotes: BTreeMap<String, McpRemoteIdentity>,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
pub struct VaultIdentity {
    pub registration_id: Ulid,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct McpRemoteIdentity {
    pub instance_id: Ulid,
    /// For a remote a vault describes: the `IndieAuth` identity this device
    /// accepted. A different one in the vault waits for
    /// `vulcan daemon apply --accept-remote`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub accepted_identity: Option<String>,
}

#[must_use]
pub fn identities_path(config_path: &Path) -> PathBuf {
    config_path.with_file_name(IDENTITIES_FILE)
}

pub fn parse_identities(source: Option<&str>) -> Result<Identities, String> {
    source.map_or_else(
        || Ok(Identities::default()),
        |source| toml::from_str(source).map_err(|error| error.to_string()),
    )
}

pub fn render_identities(identities: &Identities) -> Result<String, String> {
    let body = toml::to_string_pretty(identities).map_err(|error| error.to_string())?;
    Ok(format!("{IDENTITIES_HEADER}\n{body}"))
}

/// Whether a `daemon.toml` document still carries generated identities, as
/// files written before identities moved out do.
#[must_use]
pub fn has_generated_keys(source: &str) -> bool {
    source.parse::<DocumentMut>().is_ok_and(|document| {
        GENERATED_KEYS.iter().any(|(array, key)| {
            document
                .get(array)
                .and_then(Item::as_array_of_tables)
                .is_some_and(|tables| tables.iter().any(|table| table.contains_key(key)))
        })
    })
}

/// Removes generated identities from a `daemon.toml` document and changes
/// nothing else, for the one-time migration of older files.
pub fn strip_generated(source: &str) -> Result<String, String> {
    let mut document = source
        .parse::<DocumentMut>()
        .map_err(|error| error.to_string())?;
    strip_generated_keys(&mut document);
    Ok(document.to_string())
}

/// Renders `config` for `daemon.toml` without generated identities. With an
/// existing document, only what changed is rewritten: comments, key order,
/// and value formatting of unchanged entries are kept.
pub fn render_config<T: Serialize>(existing: Option<&str>, config: &T) -> Result<String, String> {
    let rendered = toml::to_string_pretty(config).map_err(|error| error.to_string())?;
    let mut desired = rendered
        .parse::<DocumentMut>()
        .map_err(|error| error.to_string())?;
    strip_generated_keys(&mut desired);
    drop_empty_declaration_arrays(&mut desired);
    let Some(existing) = existing else {
        return Ok(desired.to_string());
    };
    let mut document = existing
        .parse::<DocumentMut>()
        .map_err(|error| error.to_string())?;
    strip_generated_keys(&mut document);
    let mut next_position = max_position(document.as_table()) + 1;
    merge_table(
        document.as_table_mut(),
        desired.as_table(),
        None,
        &mut next_position,
    );
    Ok(document.to_string().trim_start_matches('\n').to_string())
}

/// The part of `daemon.toml` a `--target device` config write edits.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DeviceSection {
    /// The device-global `[permissions]` table, valid for every vault.
    Permissions,
    /// The `config` table of the `[[vault]]` entry for this vault root.
    Vault(PathBuf),
}

impl DeviceSection {
    /// Permission profiles are device-wide; every other setting belongs to
    /// the vault's own entry.
    #[must_use]
    pub fn for_key(storage_segments: &[&str], vault_root: &Path) -> Self {
        if storage_segments.first() == Some(&"permissions") {
            Self::Permissions
        } else {
            Self::Vault(vault_root.to_path_buf())
        }
    }
}

/// Reads a device section as a document with the schema of
/// `config.local.toml` (empty when absent).
pub fn read_device_section(
    config_path: &Path,
    section: &DeviceSection,
) -> Result<toml::Value, String> {
    let source = read_optional(config_path)?;
    let document = match source.as_deref() {
        Some(source) => toml::from_str::<toml::Value>(source).map_err(|error| error.to_string())?,
        None => toml::Value::Table(toml::map::Map::new()),
    };
    let mut result = toml::map::Map::new();
    match section {
        DeviceSection::Permissions => {
            if let Some(permissions) = document.get("permissions") {
                result.insert("permissions".to_string(), permissions.clone());
            }
        }
        DeviceSection::Vault(root) => {
            let entry = document
                .get("vault")
                .and_then(toml::Value::as_array)
                .and_then(|entries| {
                    entries.iter().find(|entry| {
                        entry
                            .get("path")
                            .and_then(toml::Value::as_str)
                            .is_some_and(|declared| same_vault(declared, root))
                    })
                })
                .ok_or_else(|| not_registered(config_path, root))?;
            if let Some(toml::Value::Table(config)) = entry.get("config") {
                result.clone_from(config);
            }
        }
    }
    Ok(toml::Value::Table(result))
}

/// Writes a device section back under the daemon.toml lock, keeping the
/// rest of the file as written. An empty document removes the section.
pub fn write_device_section(
    config_path: &Path,
    section: &DeviceSection,
    document: &toml::Value,
) -> Result<(), String> {
    let _lock = DaemonConfigLock::acquire(config_path).map_err(|error| error.to_string())?;
    let source = read_optional(config_path)?.unwrap_or_default();
    let mut file = source
        .parse::<DocumentMut>()
        .map_err(|error| error.to_string())?;
    let rendered = toml::to_string_pretty(document).map_err(|error| error.to_string())?;
    let desired = rendered
        .parse::<DocumentMut>()
        .map_err(|error| error.to_string())?;
    let before_value = toml::from_str::<toml::Value>(&source).map_err(|error| error.to_string())?;
    let mut next_position = max_position(file.as_table()) + 1;
    match section {
        DeviceSection::Permissions => {
            match (file.get_mut("permissions"), desired.get("permissions")) {
                (Some(current), Some(wanted)) => {
                    merge_item(current, wanted, None, &mut next_position);
                }
                (None, Some(wanted)) => {
                    let mut item = wanted.clone();
                    place(&mut item, None, &mut next_position);
                    file.insert("permissions", item);
                }
                (Some(_), None) => {
                    file.remove("permissions");
                }
                (None, None) => {}
            }
        }
        DeviceSection::Vault(root) => {
            let entry = file
                .get_mut("vault")
                .and_then(Item::as_array_of_tables_mut)
                .and_then(|entries| {
                    entries.iter_mut().find(|entry| {
                        entry
                            .get("path")
                            .and_then(Item::as_str)
                            .is_some_and(|declared| same_vault(declared, root))
                    })
                })
                .ok_or_else(|| not_registered(config_path, root))?;
            let mut wanted = desired.as_table().clone();
            // Only a header for subtables, never an empty `[vault.config]`.
            wanted.set_implicit(true);
            let anchor = Some(subtree_end(entry));
            match entry.get_mut("config") {
                _ if wanted.is_empty() => {
                    entry.remove("config");
                }
                Some(current) => {
                    merge_item(current, &Item::Table(wanted), anchor, &mut next_position);
                }
                None => {
                    let mut item = Item::Table(wanted);
                    place(&mut item, anchor, &mut next_position);
                    entry.insert("config", item);
                }
            }
        }
    }
    let rendered_file = file.to_string();
    let after_value =
        toml::from_str::<toml::Value>(&rendered_file).map_err(|error| error.to_string())?;
    if let Some(warning) =
        check_managed_edit(config_path, Some(&source), &before_value, &after_value)?
    {
        push_warning(warning);
    }
    vulcan_core::durable::replace(
        config_path,
        rendered_file.trim_start_matches('\n').as_bytes(),
        vulcan_core::durable::Durability::Full,
    )
    .map_err(|error| error.to_string())
}

fn read_optional(path: &Path) -> Result<Option<String>, String> {
    match std::fs::read_to_string(path) {
        Ok(source) => Ok(Some(source)),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(error) => Err(format!("failed to read {}: {error}", path.display())),
    }
}

fn same_vault(declared: &str, root: &Path) -> bool {
    match (
        std::fs::canonicalize(vulcan_core::config::expand_home(declared)),
        std::fs::canonicalize(root),
    ) {
        (Ok(declared), Ok(root)) => declared == root,
        _ => false,
    }
}

fn not_registered(config_path: &Path, root: &Path) -> String {
    format!(
        "{} is not registered in {}; register it with `vulcan vault add`, or use --target local",
        root.display(),
        config_path.display()
    )
}

/// The serializer writes an empty `vault = []` or `mcp_remote = []` when
/// none is declared; leave such a key out of the file instead.
fn drop_empty_declaration_arrays(document: &mut DocumentMut) {
    for (array, _) in GENERATED_KEYS {
        let empty = match document.get(array) {
            Some(Item::Value(Value::Array(values))) => values.is_empty(),
            Some(Item::ArrayOfTables(tables)) => tables.is_empty(),
            _ => false,
        };
        if empty {
            document.remove(array);
        }
    }
}

fn strip_generated_keys(document: &mut DocumentMut) {
    for (array, key) in GENERATED_KEYS {
        if let Some(tables) = document
            .get_mut(array)
            .and_then(Item::as_array_of_tables_mut)
        {
            for table in tables.iter_mut() {
                table.remove(key);
            }
        }
    }
}

/// `anchor` is where tables new to `existing` go: `None` at the document
/// root (after everything else), otherwise the end of `existing`'s own
/// subtree. A new table must stay inside its parent's block, or TOML would
/// attach a subtable of one `[[vault]]` entry to the last entry instead.
fn merge_table(
    existing: &mut Table,
    desired: &Table,
    anchor: Option<usize>,
    next_position: &mut usize,
) {
    let stale = existing
        .iter()
        .map(|(key, _)| key.to_string())
        .filter(|key| !desired.contains_key(key))
        .collect::<Vec<_>>();
    for key in stale {
        existing.remove(&key);
    }
    for (key, wanted) in desired {
        if let Some(current) = existing.get_mut(key) {
            merge_item(current, wanted, anchor, next_position);
        } else {
            let mut item = wanted.clone();
            place(&mut item, anchor, next_position);
            existing.insert(key, item);
        }
    }
}

fn merge_item(current: &mut Item, wanted: &Item, anchor: Option<usize>, next_position: &mut usize) {
    match (&mut *current, wanted) {
        (Item::Table(current), Item::Table(wanted)) => {
            let own = Some(subtree_end(current));
            merge_table(current, wanted, own, next_position);
        }
        (Item::ArrayOfTables(current), Item::ArrayOfTables(wanted)) => {
            merge_array_of_tables(current, wanted, next_position);
        }
        (Item::Value(current), Item::Value(wanted)) => merge_value(current, wanted),
        // An owner may write a subtable inline; keep that form.
        (Item::Value(current @ Value::InlineTable(_)), Item::Table(wanted)) => {
            merge_value(
                current,
                &Value::InlineTable(wanted.clone().into_inline_table()),
            );
        }
        (current, wanted) => {
            let mut item = wanted.clone();
            place(&mut item, anchor, next_position);
            *current = item;
        }
    }
}

fn place(item: &mut Item, anchor: Option<usize>, next_position: &mut usize) {
    match anchor {
        None => assign_positions(item, next_position),
        Some(position) => pin_positions(item, position),
    }
}

/// Gives every table in `item` the same position: rendering is a stable sort
/// by position over a depth-first walk, so they follow their parent's
/// existing tables in order.
fn pin_positions(item: &mut Item, position: usize) {
    match item {
        Item::Table(table) => pin_table_positions(table, position),
        Item::ArrayOfTables(tables) => {
            for table in tables.iter_mut() {
                pin_table_positions(table, position);
            }
        }
        Item::None | Item::Value(_) => {}
    }
}

fn pin_table_positions(table: &mut Table, position: usize) {
    table.set_position(position);
    separate(table);
    for (_, item) in table.iter_mut() {
        pin_positions(item, position);
    }
}

/// Starts a table the writer adds with a blank line, as a person would.
fn separate(table: &mut Table) {
    let unset = table
        .decor()
        .prefix()
        .and_then(|prefix| prefix.as_str())
        .is_none_or(str::is_empty);
    if !table.is_implicit() && unset {
        table.decor_mut().set_prefix("\n");
    }
}

fn subtree_end(table: &Table) -> usize {
    table.position().unwrap_or(0).max(max_position(table))
}

fn merge_value(current: &mut Value, wanted: &Value) {
    if values_equal(current, wanted) || home_relative_equal(current, wanted) {
        return;
    }
    let decor = current.decor().clone();
    *current = wanted.clone();
    *current.decor_mut() = decor;
}

/// Matches array elements by their `id`, falling back to position, so editing
/// one vault or remote leaves the others' formatting untouched.
fn merge_array_of_tables(
    current: &mut ArrayOfTables,
    wanted: &ArrayOfTables,
    next_position: &mut usize,
) {
    let mut previous = current.iter().cloned().map(Some).collect::<Vec<_>>();
    let mut merged = ArrayOfTables::new();
    for (index, table) in wanted.iter().enumerate() {
        let matching = match table_id(table) {
            Some(id) => previous
                .iter()
                .position(|candidate| candidate.as_ref().and_then(table_id) == Some(id)),
            None => previous
                .get(index)
                .and_then(Option::as_ref)
                .filter(|candidate| table_id(candidate).is_none())
                .map(|_| index),
        };
        if let Some(mut existing) = matching.and_then(|position| previous[position].take()) {
            let own = Some(subtree_end(&existing));
            merge_table(&mut existing, table, own, next_position);
            merged.push(existing);
        } else {
            let mut table = table.clone();
            assign_table_positions(&mut table, next_position);
            merged.push(table);
        }
    }
    // Array order is file order. When kept and new elements no longer appear
    // in the wanted order, move the whole array after the existing tables.
    if !in_file_order(&merged) {
        for table in merged.iter_mut() {
            assign_table_positions(table, next_position);
        }
    }
    *current = merged;
}

fn in_file_order(tables: &ArrayOfTables) -> bool {
    let mut previous_end = None;
    for table in tables {
        let Some(start) = table.position() else {
            return false;
        };
        if previous_end.is_some_and(|end| start <= end) {
            return false;
        }
        previous_end = Some(start.max(max_position(table)));
    }
    true
}

/// A path written as `~/...` is loaded expanded; keep the owner's form when
/// it still names the same path.
fn home_relative_equal(current: &Value, wanted: &Value) -> bool {
    match (current, wanted) {
        (Value::String(current), Value::String(wanted)) => {
            current.value().starts_with('~')
                && vulcan_core::config::expand_home(current.value()) == Path::new(wanted.value())
        }
        _ => false,
    }
}

fn table_id(table: &Table) -> Option<&str> {
    table.get("id").and_then(Item::as_str)
}

fn values_equal(left: &Value, right: &Value) -> bool {
    match (left, right) {
        (Value::String(left), Value::String(right)) => left.value() == right.value(),
        (Value::Integer(left), Value::Integer(right)) => left.value() == right.value(),
        (Value::Float(left), Value::Float(right)) => {
            left.value().to_bits() == right.value().to_bits()
        }
        (Value::Boolean(left), Value::Boolean(right)) => left.value() == right.value(),
        (Value::Datetime(left), Value::Datetime(right)) => left.value() == right.value(),
        (Value::Array(left), Value::Array(right)) => {
            left.len() == right.len()
                && left
                    .iter()
                    .zip(right.iter())
                    .all(|(left, right)| values_equal(left, right))
        }
        (Value::InlineTable(left), Value::InlineTable(right)) => {
            left.len() == right.len()
                && left.iter().all(|(key, value)| {
                    right
                        .get(key)
                        .is_some_and(|other| values_equal(value, other))
                })
        }
        _ => false,
    }
}

/// Tables carried over from the freshly rendered document keep that
/// document's positions; renumber them so they follow the existing ones.
fn assign_positions(item: &mut Item, next_position: &mut usize) {
    match item {
        Item::Table(table) => assign_table_positions(table, next_position),
        Item::ArrayOfTables(tables) => {
            for table in tables.iter_mut() {
                assign_table_positions(table, next_position);
            }
        }
        Item::None | Item::Value(_) => {}
    }
}

fn assign_table_positions(table: &mut Table, next_position: &mut usize) {
    table.set_position(*next_position);
    separate(table);
    *next_position += 1;
    for (_, item) in table.iter_mut() {
        assign_positions(item, next_position);
    }
}

fn max_position(table: &Table) -> usize {
    table
        .iter()
        .map(|(_, item)| match item {
            Item::Table(table) => table.position().unwrap_or(0).max(max_position(table)),
            Item::ArrayOfTables(tables) => tables
                .iter()
                .map(|table| table.position().unwrap_or(0).max(max_position(table)))
                .max()
                .unwrap_or(0),
            Item::None | Item::Value(_) => 0,
        })
        .max()
        .unwrap_or(0)
}

